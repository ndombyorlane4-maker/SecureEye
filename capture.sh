            *"Huawei"*) device_type="📱 Huawei" ;;
            *"Xiaomi"*) device_type="📱 Xiaomi" ;;
            *"Google"*) device_type="📱 Google/Pixel" ;;
            *"TP-Link"*) device_type="🔵 Router" ;;
            *"Netgear"*) device_type="🔵 Router" ;;
            *"D-Link"*) device_type="🔵 Router" ;;
            *"Cisco"*) device_type="🔵 Router" ;;
            *"Dell"*) device_type="💻 Computer" ;;
            *"Hewlett"*) device_type="💻 Computer" ;;
            *"Lenovo"*) device_type="💻 Computer" ;;
            *"Hotspot"*) device_type="📱 Mobile Hotspot" ;;
        esac
        
        printf "%-20s | %-17s | %-25s | %-15s\n" "$ip" "$mac" "$manufacturer" "$device_type"
        
        count=$((count + 1))
        scan_results="${scan_results}${ip}|${mac}|${manufacturer}|${device_type}\n"
        
    done <<< "$scan_output"
    
    echo "─────────────────────────────────────────────────────────────"
    echo "📊 Total devices found: $count"
    echo "═══════════════════════════════════════════════════════════"
    echo ""
    
    # Envoyer les résultats à VM2
    if [ -n "$scan_results" ] && [ -n "$VM2_IP" ]; then
        send_scan_to_vm2 "$scan_results"
    fi
}

# =============================================================================
# 5. SCAN PÉRIODIQUE
# =============================================================================

run_periodic_scan() {
    while true; do
        sleep 600
        scan_network "$IFACE" > /dev/null 2>&1
    done
}

