echo ""
echo "═══════════════════════════════════════════════════════════"
echo "🔍 CAPTURE - Network Capture Agent"
echo "═══════════════════════════════════════════════════════════"
echo "📡 Interface: $IFACE"
echo "🎯 Target: SECURE-EYE-XX ($VM2_IP:$VM2_UDP_PORT)"
echo "═══════════════════════════════════════════════════════════"
echo ""

# Scan initial
scan_network "$IFACE"

# Démarrer le scan périodique en arrière-plan
run_periodic_scan &
SCAN_PID=$!

# Capture continue
echo "📡 CAPTURING PACKETS (press Ctrl+C to stop)"
echo "─────────────────────────────────────────────────────────────────────────────"
printf "%-20s | %-15s | %-15s | %-8s | %-6s | %-12s\n" \
    "TIME" "SOURCE" "DESTINATION" "PROTOCOL" "LEN" "FLAGS"
echo "─────────────────────────────────────────────────────────────────────────────"

tshark -i "$IFACE" -T fields \
  -e frame.time_epoch \
  -e ip.src \
  -e ip.dst \
  -e ip.proto \
  -e frame.len \
  -e tcp.flags \
  -E separator='|' \
  -E quote=n \
  -l -q 2>/dev/null | while IFS='|' read -r ts src dst proto len tcp_flags; do
    
    ts=$(echo "$ts" | xargs)
    src=$(echo "$src" | xargs)
    dst=$(echo "$dst" | xargs)
    proto=$(echo "$proto" | xargs)
    len=$(echo "$len" | xargs)
    tcp_flags=$(echo "$tcp_flags" | xargs)
    
    [ -z "$ts" ] && continue
    
    if [[ "$ts" =~ ^[0-9]+\. ]]; then
        SECONDS=${ts%.*}
        HUMAN_TIME=$(date -d "@$SECONDS" "+%H:%M:%S" 2>/dev/null)
        TIME="$HUMAN_TIME"
    else
        TIME="$ts"
    fi
    
    case "$proto" in
        "6")  PROTO="TCP" ;;
        "17") PROTO="UDP" ;;
        "1")  PROTO="ICMP" ;;
        *)    PROTO="Proto-$proto" ;;
    esac
    
    if [ "$PROTO" = "TCP" ]; then
        case "$tcp_flags" in
            "0x002") FLAGS="SYN" ;;
            "0x012") FLAGS="SYN-ACK" ;;
            "0x010") FLAGS="ACK" ;;
            "0x004") FLAGS="RST" ;;
            "0x001") FLAGS="FIN" ;;
            "0x018") FLAGS="PSH-ACK" ;;
            *) FLAGS="$tcp_flags" ;;
        esac
    else
        FLAGS="—"
    fi
    
    printf "%-20s | %-15s | %-15s | %-8s | %-6s | %-12s\n" \
        "$TIME" "$src" "$dst" "$PROTO" "$len" "$FLAGS"
    
    # Envoyer à VM2
    packet_data="$ts|$src|$dst|$proto|$len|$tcp_flags"
    send_to_vm2 "$packet_data" &
    
done
