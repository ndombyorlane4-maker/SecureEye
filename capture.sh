find_active_interface() {
    local iface=$(ip route | grep default | awk '{print $5}' | head -1)
    if [ -n "$iface" ] && ip link show "$iface" 2>/dev/null | grep -q "UP"; then
        echo "$iface"
        return 0
    fi
    
    for iface in $(ip -o -4 addr show | grep -v lo | awk '{print $2}'); do
        if ip link show "$iface" 2>/dev/null | grep -q "UP"; then
            echo "$iface"
            return 0
        fi
    done
    
    echo "any"
}

if [ -z "$1" ]; then
    IFACE=$(find_active_interface)
    echo "🔍 Auto-detected active interface: $IFACE"
else
    IFACE="$1"
    if ! ip link show "$IFACE" 2>/dev/null | grep -q "UP"; then
        echo "⚠️  Warning: Interface $IFACE is DOWN"
        IFACE=$(find_active_interface)
        echo "📡 Using active interface: $IFACE"
    fi
fi

if [ "$EUID" -ne 0 ]; then 
    echo "❌ Please run as root (sudo ./capture.sh)"
    exit 1
fi

if ! command -v tshark &> /dev/null; then
    echo "❌ tshark not found. Install with: sudo apt install tshark"
    exit 1
fi

